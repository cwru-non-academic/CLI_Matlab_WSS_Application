function config = createConfig(options)
%CREATECONFIG Map parsed application options to the reusable wrapper contract.
config = wss.WssConfig('ConfigPath', options.ConfigPath, 'CsLibDir', options.CsLibDir, ...
    'LogPath', options.LogPath, 'SerialPort', options.SerialPort, ...
    'Transport', options.Transport, 'BleAutoSelect', options.BleAutoSelect, ...
    'BleDeviceName', options.BleDeviceName, 'BleDeviceId', options.BleDeviceId, ...
    'MaxSetupTries', options.MaxSetupTries, 'TickIntervalMs', options.TickIntervalMs);
end
